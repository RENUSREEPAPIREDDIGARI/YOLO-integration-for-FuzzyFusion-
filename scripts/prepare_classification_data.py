from __future__ import annotations

import argparse
import random
import shutil
from pathlib import Path

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"}
MARKER = ".yolo-classification-dataset"
ROOT = Path(__file__).resolve().parents[1]


def prepare_classification_data(
    source: Path,
    output: Path,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    seed: int = 42,
) -> dict[str, int]:
    source = source.expanduser().resolve()
    output = output.expanduser().resolve()
    test_ratio = 1.0 - train_ratio - val_ratio
    if not 0 < train_ratio < 1 or not 0 < val_ratio < 1 or test_ratio <= 0:
        raise ValueError("train_ratio and val_ratio must be positive and sum to less than 1.")
    if not source.is_dir():
        raise FileNotFoundError(f"Source dataset folder not found: {source}")
    if source == output or source in output.parents or output in source.parents:
        raise ValueError("The source and prepared output folders must not overlap.")

    classes = sorted(path for path in source.iterdir() if path.is_dir())
    class_images = {
        folder: sorted(
            path
            for path in folder.rglob("*")
            if path.is_file() and path.suffix.lower() in IMAGE_EXTENSIONS
        )
        for folder in classes
    }
    class_images = {folder: images for folder, images in class_images.items() if images}
    if len(class_images) < 2:
        raise ValueError(f"Expected at least two class folders with images in {source}")
    for folder, images in class_images.items():
        if len(images) < 3:
            raise ValueError(
                f"Class '{folder.name}' has {len(images)} images; at least 3 are needed "
                "for train/validation/test splits."
            )

    output.mkdir(parents=True, exist_ok=True)
    marker_path = output / MARKER
    if any(output.iterdir()) and not marker_path.is_file():
        raise FileExistsError(
            f"Refusing to overwrite an unmarked output folder: {output}"
        )
    if marker_path.is_file():
        shutil.rmtree(output)
    output.mkdir(parents=True, exist_ok=True)
    (output / MARKER).write_text(
        "Generated by scripts/prepare_classification_data.py\n", encoding="utf-8"
    )

    counts = {"train": 0, "val": 0, "test": 0}
    rng = random.Random(seed)
    for class_dir, images in class_images.items():
        shuffled = images.copy()
        rng.shuffle(shuffled)
        ratios = (train_ratio, val_ratio, test_ratio)
        split_counts = [max(1, int(len(shuffled) * ratio)) for ratio in ratios]
        while sum(split_counts) > len(shuffled):
            largest_split = max(range(3), key=split_counts.__getitem__)
            split_counts[largest_split] -= 1
        while sum(split_counts) < len(shuffled):
            next_split = max(
                range(3),
                key=lambda index: len(shuffled) * ratios[index] - split_counts[index],
            )
            split_counts[next_split] += 1
        train_end = split_counts[0]
        val_end = train_end + split_counts[1]
        splits = {
            "train": shuffled[:train_end],
            "val": shuffled[train_end:val_end],
            "test": shuffled[val_end:],
        }
        for split, split_images in splits.items():
            destination = output / split / class_dir.name
            destination.mkdir(parents=True, exist_ok=True)
            for image in split_images:
                relative_image = image.relative_to(class_dir)
                image_destination = destination / relative_image
                image_destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(image, image_destination)
            counts[split] += len(split_images)

    print(f"Prepared {sum(counts.values())} images from {len(class_images)} classes at {output}")
    print(f"Split counts: train={counts['train']}, val={counts['val']}, test={counts['test']}")
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Create a reproducible train/validation/test split from class folders."
    )
    parser.add_argument("source", type=Path, help="Source folder containing one directory per class.")
    parser.add_argument("--output", type=Path, default=ROOT / "data" / "colorectal-cls")
    parser.add_argument("--train-ratio", type=float, default=0.7)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    prepare_classification_data(
        source=args.source,
        output=args.output,
        train_ratio=args.train_ratio,
        val_ratio=args.val_ratio,
        seed=args.seed,
    )


if __name__ == "__main__":
    main()
